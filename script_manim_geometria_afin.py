        label_Q = MathTex('Q', color=TEAL).next_to(punto_Q, UP)
        self.play(FadeIn(punto_P), Write(label_P))
        self.wait(2)
        self.play(GrowArrow(vector_v), Write(label_v))
        self.play(FadeIn(punto_Q), Write(label_Q))
        self.wait(3)
        eq1 = MathTex('P + \\vec{v} = Q', color=YELLOW).to_corner(UR).shift(LEFT * 0.5)
        eq2 = MathTex('Q - P = \\vec{v}', color=YELLOW).next_to(eq1, DOWN, aligned_edge=LEFT)
