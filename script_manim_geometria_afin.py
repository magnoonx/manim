        ax1 = MathTex(r'1. \text{ Identidad: } P + \vec{0} = P', color=WHITE).scale(0.8)
        ax2 = MathTex(r'2. \text{ Asociatividad: } (P + \vec{u}) + \vec{v} = P + (\vec{u} + \vec{v})', color=WHITE).scale(0.8)
        grupo_ax = VGroup(ax1, ax2).arrange(DOWN, aligned_edge=LEFT, buff=0.4).next_to(axiomas_tit, DOWN, buff=0.5).to_edge(LEFT)
        ax3 = MathTex(r'3. \text{ Existencia y Unicidad: } \exists! \vec{v} \in V \text{ tal que } P + \vec{v} = Q', color=WHITE).scale(0.8).arrange(DOWN, aligned_edge=LEFT, buff=0.4).next_to(axiomas_tit, DOWN, buff=0.5).to_edge(DOWN)
