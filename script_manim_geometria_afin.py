        self.play(Write(def_bari))
        self.wait(5)
        self.play(FadeOut(def_bari))
        p0 = np.array([-2, -1.5, 0])
        p1 = np.array([3, -1.5, 0])
        p2 = np.array([0.5, 2.5, 0])
