            r'(A, V, +)',
            r'\text{Donde:}',
            r'\bullet \ A: \text{Conjunto de Puntos}',
            r'\bullet \ V: \text{Espacio Vectorial}',
            r'\bullet \ + : A \times V \rightarrow A',
            color=WHITE
