        self.play(Create(plano))
        self.play(FadeIn(origen_dot), Write(origen_label))
        self.wait(4)
        self.play(FadeOut(plano), FadeOut(origen_dot), FadeOut(origen_label), FadeOut(origen_txt))
        definicion_tit = Text('Definición Formal', color=YELLOW).to_edge(UP)
